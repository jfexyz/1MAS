// Writes Sources/UnoMasKit/ModelTable.swift, the table of 1MORE models, from PairFree's model data:
//
//   curl -o /tmp/devices.json 'https://raw.githubusercontent.com/Omega-Destroyer/PairFree/main/data/1more/devices.json'
//   swift scripts/import-models.swift /tmp/devices.json
//
// PairFree (GPLv3) took this data from 1MORE's product list and decompiled apps; it has not tested
// the models either. Only facts are carried over: names, model numbers, and which controls each
// model has. Models reached through Tuya's platform get no entry, only their names, so that they
// are not taken for unknown 1MORE models. The models in `verified` are marked as checked on real
// headphones; add one only with its evidence in docs/HARDWARE.md.

import Foundation

let verified: Set<String> = ["HC905"]

let arguments = CommandLine.arguments
guard arguments.count >= 2 else {
    print("usage: swift scripts/import-models.swift <devices.json> [output.swift]")
    exit(2)
}
let output = arguments.count > 2 ? arguments[2] : "Sources/UnoMasKit/ModelTable.swift"

struct ModelData: Decodable {
    var fetched: String
    var devices: [Device]
}

struct Device: Decodable {
    var name: String
    var model: String
    var aliases: [String]?
    var tuya: Bool
    var kind: String
    var listen_modes: [String]
    var dual_device: Bool
    var eq_presets: [String]?
}

let listenModes = [
    "off": ".off", "strong": ".strongANC", "mild": ".mildANC", "adaptive": ".adaptiveANC",
    "wind": ".windReduction", "transparent": ".transparent", "pass_through": ".passThrough",
    "voice_enhancement": ".voiceEnhancement",
]
let presets = [
    "studio": ".studio", "bass_reducer": ".bassReducer", "bass_booster": ".bassBooster",
    "acoustic": ".acoustic", "luca": ".soundByLuca", "classical": ".classical", "podcast": ".podcast",
    "deep": ".deep", "electronic": ".electronic", "hiphop": ".hipHop", "lounge": ".lounge", "pop": ".pop",
    "loud": ".vocalBooster",
]
// The older list, sent by position: EQPreset.classic.
let classic = [
    "default", "bass_reducer_1", "bass_reducer_2", "bass_booster_1", "bass_booster_2", "acoustic_1",
    "acoustic_2", "classical_1", "classical_2", "podcast", "vocal_booster", "deep_1", "deep_2",
    "electronic_1", "electronic_2", "hiphop_1", "hiphop_2", "lounge_1", "lounge_2", "pop_1", "pop_2", "loud",
]

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("import-models: \(message)\n".utf8))
    exit(1)
}

func lookup(_ table: [String: String], _ key: String, _ what: String) -> String {
    guard let value = table[key] else { fail(what) }
    return value
}

func quoted(_ text: String) -> String {
    "\"\(text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\""))\""
}

let data = try JSONDecoder().decode(ModelData.self, from: Data(contentsOf: URL(fileURLWithPath: arguments[1])))
let reachable = data.devices.filter { !$0.tuya }
let unreachable = data.devices.filter { $0.tuya }
for model in verified where !reachable.contains(where: { $0.model == model }) {
    fail("verified model \(model) is not in the data")
}

var entries: [String] = []
for device in reachable {
    let modes = device.listen_modes.map { lookup(listenModes, $0, "\(device.name): unknown listen mode \($0)") }
    let names = device.eq_presets ?? []
    let eq = names == classic
        ? "EQPreset.classic"
        : "[" + names.map { lookup(presets, $0, "\(device.name): unknown EQ preset \($0)") }.joined(separator: ", ") + "]"
    let kind = switch device.kind {
    case "headphones": ".headphones"
    case "earbuds": ".earbuds"
    default: fail("\(device.name): unknown kind \(device.kind)")
    }
    var fields = ["bluetoothName: \(quoted(device.name))"]
    if let aliases = device.aliases, !aliases.isEmpty {
        fields.append("aliases: [\(aliases.map(quoted).joined(separator: ", "))]")
    }
    fields += [
        "model: \(quoted(device.model))",
        "kind: \(kind)",
        "listenModes: [\(modes.joined(separator: ", "))]",
        "eqPresets: \(eq)",
        "dualDevice: \(device.dual_device)",
    ]
    if verified.contains(device.model) { fields.append("verified: true") }
    entries.append("        ModelInfo(\n" + fields.map { "            \($0)," }.joined(separator: "\n") + "\n        ),")
}

let source = """
    // Generated by scripts/import-models.swift from PairFree's data/1more/devices.json (fetched by
    // PairFree on \(data.fetched)). Run the script again rather than editing this file.

    public extension ModelInfo {
        /// Every model 1MORE's apps reach over this protocol.
        static let known: [ModelInfo] = [
    \(entries.joined(separator: "\n"))
        ]

        /// Models 1MORE's app reaches through Tuya's platform instead, which 1MAS cannot.
        static let unreachableNames: Set<String> = [\(unreachable.map { quoted($0.name) }.joined(separator: ", "))]
    }

    """
try source.write(toFile: output, atomically: true, encoding: .utf8)
print("Wrote \(reachable.count) models to \(output)")
